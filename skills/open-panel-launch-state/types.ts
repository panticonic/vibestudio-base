export type LaunchPatch=Record<string,unknown>;
export type LaunchState={title:string;owner:string;mode:string;count:number;label?:string;
  settings:{side:string;order:string;pins:string[];lastNote?:string}};
export type LaunchIndex={panelId:string;title:string;purpose:"active"|"archive"}[];
export type LaunchSnapshot={panelId:string;entryKey:string;entityId:string;contextId:string;buildKey:string;digest:string;state:LaunchState};
export type LaunchPlan={panelId:string;direction:"read"|"write"|"test";patch:LaunchPatch;retain:boolean};
export type LaunchDecision={attempt:boolean;reason:string};
export type LaunchEffect={panelId:string;basis:string;kind:"saved"|"invalid"|"stale";state:LaunchState|null;message:string|null};
export type LaunchAuthorityChoice={operationId:string;label:string};
export type LaunchAuthorityScope={capability:string;resourceKey:string};
export type LaunchAuthorityObservation={operationId:string;decision:string;leaves:{capability:string;resourceKey:string;tier:string;status:string}[]};
export type LaunchAuthorityRequest={goal:string;operations:LaunchAuthorityChoice[];ceiling:LaunchAuthorityScope[]};
export type LaunchAuthorityReport={status:string;protectedLeaves:LaunchAuthorityScope[];held:string[];
  reviews:{observation:LaunchAuthorityObservation;outside:LaunchAuthorityScope[];disposition:string}[]};
export type LaunchPreflight={request:LaunchAuthorityRequest;report:LaunchAuthorityReport};
export type LaunchVerdict={status:"confirmed"|"held"|"applied"|"rejected";summary:string};
export type LaunchNote={path:string;digest:string};
export type LaunchReport={plan:LaunchPlan;opening:LaunchSnapshot;current:LaunchSnapshot;decision:LaunchDecision;
  preflight:LaunchPreflight|null;effect:LaunchEffect|null;readback:LaunchSnapshot;result:LaunchVerdict;handoff:LaunchNote|null};
