export type PacketDocument = {path:string;version:string;text:string};
export type PacketMission = {id:string;title:string;revision:number;description:string;status:string};
export type PacketAttachment = {name:string;digest:string;pages:number;approval:"approved"|"retained"|"preview"};
export type PacketSnapshot = {mission:PacketMission;candidate:PacketDocument;attachments:PacketAttachment[];
  preview:PacketDocument;permittedFields:string[]};
export type PacketPlan = {missionId:string;operation:"revise"|"review";fields:string[];
  note:"none"|"diagnostic"|"ready-only"};
export type PacketReadRequest = {goal:string;document:string;pages:number[];batchSize:number;purpose:"text";allowOcr:boolean;query:string};
export type PacketSourcePlan = {attachment:string;pages:number[];query:string};
export type PacketCitation = {page:number;line:number;quote:string;bounds:number[];confidence:number|null;source:"embedded-text"|"ocr"};
export type PacketPdf = {digest:string;status:"encrypted"|"missing-pages"|"engine-unavailable"|"verified"|"partial-match"|"no-match"|"incomplete";
  readPages:number[];remaining:number[];citations:PacketCitation[];unanswered:string[]};
export type PacketEvidence = {status:"grounded"|"unavailable";document:PacketDocument|null;source:string|null;citations:PacketCitation[]};
export type PacketSource = {selection:PacketSourcePlan|null;request:PacketReadRequest|null;pdf:PacketPdf|null;evidence:PacketEvidence|null};
export type PacketWrite = {status:"changed"|"written"|"unavailable";version:string|null};
export type PacketEdit = {proposed:PacketDocument|null;revised:string|null;attempts:PacketWrite[];stored:PacketDocument};
export type PacketDecision = {status:"ready"|"already-current"|"held"|"reviewed";write:boolean;explanation:string};
export type PacketReceipt = {path:string;digest:string;candidateVersion:string;missionRevision:number};
export type PacketReport = {plan:PacketPlan;opening:PacketSnapshot;current:PacketSnapshot;sources:PacketSource[];
  edit:PacketEdit;decision:PacketDecision;note:PacketReceipt|null};
