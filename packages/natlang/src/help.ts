import { MODEL_ROLE_CALL_BUDGETS } from "@workspace/model-catalog/modelRoles";
import { SERVICE_NAMES } from "@workspace/natlang-services";

/**
 * What `help("nl")` and `help("natlang")` tell an agent. Model-facing text: keep
 * it short, concrete, and true to what the provider does.
 */
export function natlangHelp(): string {
  return [
    "nl and natlang: natural-language functions that a small model runs, inside your eval cell.",
    "",
    "Inline nl (ambient, no import):",
    "  const verdict: 'urgent' | 'normal' = await nl`Decide whether ${ticket} is urgent.`(ticket);",
    "  const reply = await nl<string>`Draft a short reply to ${message}.`(message);",
    "  The result type comes from your annotation or the type argument; the call is checked against it.",
    "  An inline call has NO services and no access to your bindings. It sees only what you pass as",
    "  arguments, mention in the instructions (captures), or hand over with nl`...`.with({ name: value }).",
    "  Passing a function or object passes the authority it carries.",
    "",
    "Workspace programs:",
    "  const brief = await natlang.load('skills/server-logs/brief.nl');   // a .nl file",
    "  const tools = await natlang.load('skills/server-logs');            // a folder: a record of callables",
    "  await brief({ since });",
    "  const shape = await natlang.describe('skills/server-logs');        // its functions with typed signatures (data, nothing runs)",
    "  A program is type-checked when loaded (and re-checked only when its files change). It gets exactly the",
    "  services its services.d.ts declares (declare module 'natlang:services' { export const serverLog: ... })",
    "  or its TypeScript modules import from 'natlang:services', each a narrowed view of your own binding: your",
    "  approvals and authority checks apply unchanged. Available services: " + SERVICE_NAMES.join(", ") + ".",
    "  A program returns proposals for consequential effects; you commit them.",
    "",
    "Models and budgets: calls run on the executor model by default, within its budget (" +
      `${MODEL_ROLE_CALL_BUDGETS.executor.maxTurns} turns of ${MODEL_ROLE_CALL_BUDGETS.executor.turnTokens} tokens).`,
    "  A program function's `model: NAME` frontmatter names a model role or a 'provider:id' ref, and",
    "  `budget: { maxTurns: 8, turnTokens: 1024 }` gives its calls other bounds. fn.on({ model: NAME }) is the same",
    "  function on another model, for one call: await judge.on({ model: 'standard' })(note).",
    "",
    "Results and traces:",
    "  Your result lists each root call (name, outcome or failure reason, model, turns, tokens, record id); a",
    "  finite-result (`readout: decision`) call shows the chosen value's probability and the runner-up.",
    "  await natlang.trace(callId) is a digest: inputs, each turn's actions and results, child calls, the scope",
    "  it ended with, and why it ended. { raw: true } gives the full record and event trace.",
    "  await natlang.calls({ parentCallId }) lists a call's children; { run: runId } a run's calls.",
    "",
    "When a call fails it throws NatlangCallError: 'natlang NAME: OUTCOME: DETAIL (record CALL_ID)', with",
    "e.callId, e.reason, e.detail, e.trace (the expression that reads the digest) and e.partial (its last scope).",
    "  reason                          next step",
    "  blocked / failed                the model says the inputs do not support an answer: pass the missing evidence",
    "  type-mismatch, no-action,       narrow the type or instructions, retry with .on({ model: 'standard' }),",
    "  repeated-failed-action          or do the step yourself",
    "  budget-exhausted                too much work for one call: do the exact parts in code, ask one decision",
    "  executor-unavailable            no executor model: see the local-models skill, or do the work yourself",
    "  model-unavailable               the named model is unknown or not connected",
    "  model-refused                   the gateway refused (authority or usage): final, report it, do not loop",
    "  cancelled / refused / error     cancelled; natlang did not run it; an outside error (see errorData.cause)",
    "  Recover in code:",
    "    try { return await judge(note); }",
    "    catch (e: any) {",
    "      if (e.name !== 'NatlangCallError') throw e;",
    "      const t = await natlang.trace(e.callId);",
    "      return { reason: e.reason, lastTurn: t.turns.at(-1), children: t.children, partial: e.partial };",
    "    }",
    "  natlang.rerun(callId, { model: 'standard' }) replays a program call's recorded inputs on another model.",
    "",
    "Cancelling the run stops its natlang calls. Calls cost model tokens: keep them focused, and do exact",
    "work (arithmetic, parsing, filtering) in ordinary code.",
  ].join("\n");
}
